"""
Builds the InsuranceClaims database end-to-end and exports every analysis query.

    python run_project.py                      # default server: (localdb)\\MSSQLLocalDB
    python run_project.py .\\SQLEXPRESS          # any SQL Server instance

Steps: scripts 01-03 and 05 run through sqlcmd (the data path is injected), then every
"-- Qxx:" query in 04_analysis.sql runs through pyodbc and is saved to results/Qxx_<title>.csv
plus one combined results/all_results.md that reads well on GitHub.
"""
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import pandas as pd
import pyodbc
import warnings

warnings.filterwarnings("ignore", message="pandas only supports SQLAlchemy")


def fmt(v):
    if isinstance(v, float):
        if v != v:
            return ""
        return f"{v:,.0f}" if abs(v) >= 1000 else f"{v:.4f}".rstrip("0").rstrip(".")
    return v

SERVER = sys.argv[1] if len(sys.argv) > 1 else r"(localdb)\MSSQLLocalDB"
HERE = Path(__file__).resolve().parent
SQL = HERE / "sql"
OUT = HERE / "results"
OUT.mkdir(exist_ok=True)


def run_script(name):
    text = (SQL / name).read_text(encoding="utf-8")
    data_path = "N'" + str(HERE / "data").replace("'", "''") + "\\'"
    text = re.sub(r"N'[A-Z]:\\[^']*\\data\\'", lambda _: data_path, text)
    with tempfile.NamedTemporaryFile("w", suffix=".sql", delete=False, encoding="utf-8") as f:
        f.write(text)
    r = subprocess.run(["sqlcmd", "-S", SERVER, "-E", "-b", "-f", "65001", "-i", f.name], capture_output=True, text=True)
    print(f"{name}: {'ok' if r.returncode == 0 else 'FAILED'}")
    if r.returncode:
        print(r.stdout[-2000:], r.stderr[-2000:])
        sys.exit(1)


for s in ["01_create_database.sql", "02_load_data.sql", "03_views_and_quality.sql", "05_stored_procedure.sql"]:
    run_script(s)

conn = pyodbc.connect(f"DRIVER={{ODBC Driver 17 for SQL Server}};SERVER={SERVER};DATABASE=InsuranceClaims;"
                      "Trusted_Connection=yes;TrustServerCertificate=yes;")
script = (SQL / "04_analysis.sql").read_text(encoding="utf-8")
blocks = re.findall(r"-- (Q\d+): (.+?)\n(.*?)\nGO", script, flags=re.S)
md = ["# Query results\n", "Generated by `run_project.py` from `sql/04_analysis.sql`.\n"]
for qid, title, body in blocks:
    df = pd.read_sql(body, conn)
    slug = re.sub(r"[^A-Za-z0-9]+", "_", title)[:45].strip("_")
    df.to_csv(OUT / f"{qid}_{slug}.csv", index=False)
    md += [f"\n## {qid}: {title}\n", df.head(30).map(fmt).to_markdown(index=False), ""]
    print(f"{qid}: {len(df)} rows")
(OUT / "all_results.md").write_text("\n".join(md), encoding="utf-8")
print("done ->", OUT)

