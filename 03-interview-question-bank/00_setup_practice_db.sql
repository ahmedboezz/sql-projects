CREATE TABLE dbo.Departments (dept_id INT PRIMARY KEY, dept_name NVARCHAR(50) NOT NULL);
CREATE TABLE dbo.Employees (emp_id INT PRIMARY KEY, full_name NVARCHAR(100), email NVARCHAR(100), dept_id INT REFERENCES dbo.Departments(dept_id),
                            manager_id INT NULL, salary DECIMAL(10,2), hire_date DATE, city NVARCHAR(50));
CREATE TABLE dbo.Customers (customer_id INT PRIMARY KEY, customer_name NVARCHAR(100), email NVARCHAR(100), city NVARCHAR(50), signup_date DATE);
CREATE TABLE dbo.Products (product_id INT PRIMARY KEY, product_name NVARCHAR(100), category NVARCHAR(50), price DECIMAL(10,2));
CREATE TABLE dbo.Orders (order_id INT PRIMARY KEY, customer_id INT REFERENCES dbo.Customers(customer_id), order_date DATE,
                         status NVARCHAR(20), shipped_date DATE NULL);
CREATE TABLE dbo.OrderItems (order_id INT REFERENCES dbo.Orders(order_id), product_id INT REFERENCES dbo.Products(product_id),
                             qty INT, unit_price DECIMAL(10,2), PRIMARY KEY (order_id, product_id));
CREATE TABLE dbo.Logins (user_id INT, login_date DATE, PRIMARY KEY (user_id, login_date));
CREATE TABLE dbo.Targets (dept_id INT PRIMARY KEY, Q1 INT, Q2 INT, Q3 INT, Q4 INT);
