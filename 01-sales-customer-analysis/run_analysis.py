"""
Runs every query in sql/04_analysis.sql against SQL Server and saves each
result to results/Qxx_<title>.csv, plus one combined markdown file
(results/all_results.md) that is easy to read on GitHub.

Usage:  python run_analysis.py [server]      (default server: .\\SQLEXPRESS)
"""
import re
import sys
from pathlib import Path

import pandas as pd
import pyodbc

SERVER = sys.argv[1] if len(sys.argv) > 1 else r".\SQLEXPRESS"
HERE = Path(__file__).resolve().parent
OUT = HERE / "results"
OUT.mkdir(exist_ok=True)

conn = pyodbc.connect(
    f"DRIVER={{ODBC Driver 17 for SQL Server}};SERVER={SERVER};DATABASE=SalesAnalytics;"
    "Trusted_Connection=yes;TrustServerCertificate=yes;"
)

script = (HERE / "sql" / "04_analysis.sql").read_text(encoding="utf-8")
batches = re.split(r"^\s*GO\s*$", script, flags=re.MULTILINE | re.IGNORECASE)

md = ["# Query results\n", "Generated by `run_analysis.py` from `sql/04_analysis.sql`.\n"]
for batch in batches:
    m = re.search(r"--\s*(Q\d+):\s*(.+)", batch)
    if not m:
        continue
    qid, title = m.group(1), m.group(2).strip()
    df = pd.read_sql(batch, conn)
    slug = re.sub(r"[^A-Za-z0-9]+", "_", title.split(" - ")[0]).strip("_")[:40]
    df.to_csv(OUT / f"{qid}_{slug}.csv", index=False, encoding="utf-8")
    md += [f"\n## {qid}: {title}\n", df.to_markdown(index=False, floatfmt=",.1f"), ""]
    print(f"\n=== {qid}: {title}\n{df.to_string(index=False)}")

(OUT / "all_results.md").write_text("\n".join(md), encoding="utf-8")
